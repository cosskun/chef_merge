  final int star1Score;  // 1 Yıldız Barajı (%40) - Altında kalırsa geçemez
  final int star2Score;  // 2 Yıldız Hedefi (%70)
  final int star3Score;  // 3 Yıldız Hedefi (%100)
  final List<GameItem> rawPool;
