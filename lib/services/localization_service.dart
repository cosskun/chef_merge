import 'package:flutter/material.dart';
import 'save_service.dart';

class LanguageOption {
  final String code;
  final String name;
  final String flag;

  const LanguageOption({
    required this.code,
    required this.name,
    required this.flag,
  });
}

class LocalizationService {
  static const List<LanguageOption> supportedLanguages = [
    LanguageOption(code: 'tr', name: 'Türkçe', flag: '🇹🇷'),
    LanguageOption(code: 'en', name: 'English', flag: '🇬🇧'),
    LanguageOption(code: 'es', name: 'Español', flag: '🇪🇸'),
    LanguageOption(code: 'de', name: 'Deutsch', flag: '🇩🇪'),
  ];

  static final ValueNotifier<String> currentLanguage = ValueNotifier<String>('tr');

  static void init() {
    currentLanguage.value = SaveService.getLanguage();
  }

  static Future<void> setLanguage(String code) async {
    if (currentLanguage.value != code) {
      currentLanguage.value = code;
      await SaveService.saveLanguage(code);
    }
  }

  static String get lang => currentLanguage.value;

  static LanguageOption get currentOption {
    return supportedLanguages.firstWhere(
      (l) => l.code == currentLanguage.value,
      orElse: () => supportedLanguages.first,
    );
  }

  /// Translate a string key. Example: tr('play')
  static String tr(String key) {
    final langCode = currentLanguage.value;
    final dict = _translations[langCode] ?? _translations['tr']!;
    return dict[key] ?? _translations['en']?[key] ?? _translations['tr']?[key] ?? key;
  }

  /// Localized Item Names by Item ID
  static String getItemName(String itemId, [String fallback = '']) {
    final langCode = currentLanguage.value;
    final map = _itemNames[langCode] ?? _itemNames['tr']!;
    return map[itemId] ?? _itemNames['en']?[itemId] ?? _itemNames['tr']?[itemId] ?? fallback;
  }

